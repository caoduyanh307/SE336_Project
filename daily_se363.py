#!/usr/bin/env python3
"""Daily incremental orchestration for SE363 on an already-configured local collector.

- Collect Threads; pre-approved RSS is optional with --with-rss
- Optionally collect from permitted brand feeds, owned Meta ads and partner metadata
- Generate claim *candidates* into an autogenerated folder, never user annotations
- Queue only newly appended records as JSONL events for future Kafka producer
- Report true counts and errors; no fabricated records, no access-control bypass

No additional pip dependencies. Run from project root: python daily_se363.py --once.
"""
from __future__ import annotations
import argparse
from contextlib import closing
import csv
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import sqlite3
import subprocess
import sys
import tempfile
import time

ROOT = Path(__file__).resolve().parent
RAW = ROOT / 'data' / 'raw'
REPORTS = ROOT / 'data' / 'reports'
EVENTS = ROOT / 'data' / 'events'
LOGS = ROOT / 'data' / 'logs'
STATE = ROOT / 'data' / 'state' / 'daily_offsets.json'
INPUTS = {
    'posts_auto.jsonl': 'ad_or_promotion_candidate',
    'evidence_discovery.jsonl': 'evidence_discovery_candidate',
    'product_metadata.jsonl': 'product_metadata_record',
    'threads_posts.jsonl': 'threads_post_candidate',
    'threads_post_refs.jsonl': 'threads_post_candidate',
}


def timestamp():
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def file_size(path):
    return path.stat().st_size if path.exists() else 0


def atomic_json(path: Path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + '.tmp')
    temp.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')
    os.replace(temp, path)


def initialize_offsets(state_path: Path, raw: Path):
    """Default first-run baseline = current file end, avoids treating old records as today's new data."""
    if state_path.exists():
        try:
            state = json.loads(state_path.read_text(encoding='utf-8'))
            if isinstance(state, dict) and 'offsets' in state and isinstance(state['offsets'], dict):
                # An upgrade must not replay pre-existing Threads data or reset legacy offsets.
                added = False
                for name in INPUTS:
                    if name not in state['offsets']:
                        state['offsets'][name] = file_size(raw / name)
                        added = True
                if added:
                    atomic_json(state_path, state)
                return state
        except (OSError, ValueError):
            raise RuntimeError('Offset state bị hỏng: sao lưu và sửa, không tự reset để tránh replay sai')
    state = {'created_at': timestamp(), 'offsets': {n: file_size(raw / n) for n in INPUTS},
             'note': 'first run starts AFTER existing historical records; process old data separately for replay'}
    atomic_json(state_path, state)
    return state


def stable_record_id(row: dict, source_type: str):
    if row.get('source_platform') == 'threads' or source_type == 'threads_post_candidate':
        event_type = 'threads.post.discovered' if int(row.get('version', 1)) == 1 else 'threads.post.updated'
        return hashlib.sha256(f'threads|{row["post_id"]}|{row.get("version", 1)}|{event_type}'.encode()).hexdigest()
    identity = str(row.get('_key') or row.get('post_id') or row.get('source_url') or row.get('url') or '')
    content = str(row.get('content_hash_sha256') or row.get('raw_text') or row.get('summary') or '')
    if not identity:
        identity = json.dumps(row, ensure_ascii=False, sort_keys=True)
    return hashlib.sha256((source_type + '|' + identity + '|' + content).encode('utf-8')).hexdigest()


def emit_new_events(raw: Path, state_path: Path, events: Path, historical_replay=False):
    """Serialize Threads scanning with standalone collection and suppression."""
    from ingestion.threads_collector import CollectorError, collector_lock
    root = raw.parent.parent if raw.parent.name == 'data' else state_path.parent
    try:
        with collector_lock(root):
            if historical_replay:
                # Establish the ordinary historical baseline before replay, but
                # never rewind its cursor: a failed replay must not turn old
                # records into fresh discoveries on the next ordinary run.
                initialize_offsets(state_path, raw)
                state_path = state_path.with_name(state_path.stem + '_replay' + state_path.suffix)
                state = initialize_offsets(state_path, raw)
                state['offsets'] = {name: 0 for name in INPUTS}
                atomic_json(state_path, state)
            return _emit_new_events(raw, state_path, events, historical_replay)
    except CollectorError as exc:
        if exc.status != 'BUSY':
            raise
        # Suppression can atomically rewrite a mixed spool under the same lock.
        # Delay queueing until the next run rather than write to a replaced inode;
        # the already-run legacy collectors remain successful and no offset moves.
        dest = events / f'new_events_{datetime.now().strftime("%Y%m%d")}.jsonl'
        return {'events_new': 0, 'by_role': {}, 'spool': str(dest),
                'warnings': ['Threads scanner BUSY: giữ nguyên offsets; sự kiện nguồn cũ sẽ được đưa vào spool ở lần chạy sau']}


def _emit_new_events(raw: Path, state_path: Path, events: Path, historical_replay=False):
    """Consume only appended complete JSONL lines and save a daily event spool.

    If a source truncates, start at 0 and de-dupe event IDs already present in spool.
    Existing input lines before initial state are not labeled as new.
    """
    state = initialize_offsets(state_path, raw)
    today = datetime.now().strftime('%Y%m%d')
    events.mkdir(parents=True, exist_ok=True)
    dest = events / f'new_events_{today}.jsonl'
    problems = []
    if dest.exists():
        # An interrupted append has no durable newline or source checkpoint.
        # Remove only that unfinished tail, then recover it from the raw source.
        with dest.open('rb+') as recovery:
            complete_end = 0
            for line in recovery:
                if not line.endswith(b'\n'):
                    recovery.truncate(complete_end)
                    recovery.flush()
                    os.fsync(recovery.fileno())
                    problems.append('Đã phục hồi tail sự kiện chưa hoàn tất; đọc lại từ offset nguồn đã lưu')
                    break
                complete_end = recovery.tell()
    existing_ids = set()
    # A crash after spool fsync but before the source checkpoint can resume on a
    # different date. Ordinary retries de-dupe every source across spool dates.
    # Explicit legacy historical replay retains its intentional replay behavior.
    for previous in events.glob('*.jsonl'):
        with previous.open(encoding='utf-8') as old:
            for line in old:
                if not line.endswith('\n'):
                    # Collector outbox retries incomplete lines using its own lock.
                    break
                try:
                    prior = json.loads(line)
                    if previous == dest or not historical_replay or str(prior.get('event_type', '')).startswith('threads.post.'):
                        existing_ids.add(prior['event_id'])
                except (ValueError, KeyError, AttributeError):
                    pass
    count = 0
    breakdown = {}
    suppressed_ids = set()
    suppression_db = state_path.parent / 'threads_collector.sqlite'
    if suppression_db.exists():
        # A queued reference must not escape a later valid suppression request.
        with closing(sqlite3.connect(suppression_db.resolve().as_uri() + '?mode=ro', uri=True)) as db:
            suppressed_ids = {str(row[0]) for row in db.execute('SELECT post_id FROM suppressions')}
    with dest.open('a', encoding='utf-8') as writer:
        for filename, default_role in INPUTS.items():
            path = raw / filename
            if not path.exists():
                continue
            offset = int(state['offsets'].get(filename, 0))
            size = path.stat().st_size
            if offset > size:
                problems.append(f'{filename}: file bị ghi đè hoặc thu nhỏ; đọc lại từ đầu, de-dup bằng event_id')
                offset = 0
            with path.open('rb') as stream:
                stream.seek(offset)
                while True:
                    pos = stream.tell()
                    line = stream.readline()
                    if not line:
                        break
                    if not line.endswith(b'\n'):
                        # Do not mark an unfinished JSON line as processed.
                        stream.seek(pos)
                        break
                    try:
                        row = json.loads(line.decode('utf-8-sig'))
                        if not isinstance(row, dict):
                            raise ValueError('not an object')
                    except (ValueError, UnicodeDecodeError):
                        problems.append(f'{filename}: lỗi JSON/UTF-8 ở byte {pos}; đã bỏ qua dòng này')
                        continue
                    role = str(row.get('source_role') or default_role)
                    if (role == 'threads_post_candidate' or row.get('source_platform') == 'threads'):
                        if str(row.get('post_id', '')) in suppressed_ids or row.get('suppressed'):
                            continue
                        try:
                            if not row.get('post_id') or int(row.get('version', 1)) < 1:
                                raise ValueError('invalid Threads identity/version')
                        except (TypeError, ValueError):
                            problems.append(f'{filename}: Threads identity/version không hợp lệ ở byte {pos}; đã bỏ qua')
                            continue
                    eid = stable_record_id(row, role)
                    if eid in existing_ids:
                        continue
                    event = {
                        'event_id': eid,
                        'event_type': 'source_record_discovered',
                        'source_role': role,
                        'ingested_at': timestamp(),
                        'source_observed_at': row.get('observed_at'),
                        'source_published_at': row.get('published_at'),
                        'is_confirmed_original_ad': False,  # Must be manually verified downstream.
                        'historical_replay': historical_replay,
                        'payload': row,
                    }
                    if role == 'threads_post_candidate' or row.get('source_platform') == 'threads':
                        is_replay = historical_replay or bool(row.get('historical_replay'))
                        event.update({
                            'event_type': 'threads.post.discovered' if int(row.get('version', 1)) == 1 else 'threads.post.updated',
                            'source_platform': 'threads',
                            'source_version': int(row.get('version', 1)),
                            'post_id': row.get('post_id'),
                            'event_time': row.get('published_at') or row.get('observed_at'),
                            'ingestion_time': timestamp(),
                            'is_replay': is_replay,
                            'historical_replay': is_replay,
                            # Full text stays in permission-gated storage; spool carries references.
                            'payload': {key: row[key] for key in (
                                'post_id', 'permalink', 'published_at', 'observed_at',
                                'content_hash', 'version', 'source_platform', 'source_role',
                                'collection_permission_status', 'storage_permission_status',
                                'redistribution_status', 'post_role',
                            ) if key in row},
                        })
                    writer.write(json.dumps(event, ensure_ascii=False) + '\n')
                    writer.flush()
                    os.fsync(writer.fileno())
                    existing_ids.add(eid)
                    count += 1
                    breakdown[role] = breakdown.get(role, 0) + 1
                state['offsets'][filename] = stream.tell()
            # checkpoint after events have been flushed to avoid losing queued events
            atomic_json(state_path, state)
    return {'events_new': count, 'by_role': breakdown, 'spool': str(dest.relative_to(ROOT)) if ROOT in dest.parents else str(dest),
            'warnings': problems}


def read_configured_brands():
    cfg = ROOT / 'sources' / 'approved_brand_feeds.json'
    if not cfg.exists():
        return False
    try:
        feeds = json.loads(cfg.read_text(encoding='utf-8'))
        return isinstance(feeds, list) and any(x.get('authorized_for_collection') is True for x in feeds if isinstance(x, dict))
    except (OSError, ValueError):
        raise RuntimeError(f'Cấu hình JSON không hợp lệ: {cfg}')


def read_meta_enabled():
    if os.getenv('SE363_ENABLE_META_DAILY') != '1':
        return False
    # collector.py reads .env itself; we check config existence, without ever printing credentials.
    env = ROOT / '.env'
    if not env.exists():
        return False
    conf = {}
    for line in env.read_text(encoding='utf-8').splitlines():
        if '=' in line and not line.lstrip().startswith('#'):
            k, val = line.split('=', 1)
            conf[k.strip()] = val.strip().strip('"').strip("'")
    return bool((os.getenv('META_ACCESS_TOKEN') or conf.get('META_ACCESS_TOKEN')) and
                (os.getenv('META_AD_ACCOUNT_ID') or conf.get('META_AD_ACCOUNT_ID')))


def run_command(label, command, log, timeout=300):
    log.write(f'\n===== {label} {timestamp()} =====\n')
    log.flush()
    try:
        outcome = subprocess.run([sys.executable, *command], cwd=ROOT, text=True,
                                 stdout=log, stderr=subprocess.STDOUT, timeout=timeout,
                                 check=False, env=os.environ.copy())
        return {'exit_code': outcome.returncode, 'ok': outcome.returncode == 0}
    except subprocess.TimeoutExpired:
        log.write(f'\n[TIMEOUT] {label} exceeded {timeout} seconds\n')
        return {'exit_code': None, 'ok': False, 'error': 'timeout'}
    except OSError as exc:
        log.write(f'\n[ERROR] {label} {exc}\n')
        return {'exit_code': None, 'ok': False, 'error': str(exc)}


def daily_once(max_per_feed=50, with_partner=False, with_rss=False):
    for p in [REPORTS, EVENTS, LOGS, STATE.parent]:
        p.mkdir(parents=True, exist_ok=True)
    # Baseline pre-existing records before any subprocess can append.
    initialize_offsets(STATE, RAW)
    stamp = datetime.now().strftime('%Y%m%d_%H%M%S')
    logfile = LOGS / f'daily_{stamp}.log'
    report = {'started_at': timestamp(), 'stages': {}, 'warnings': [],
              'validation_note': 'Counts are real metadata/discovery records; not verified original ad claims.'}
    with logfile.open('w', encoding='utf-8') as log:
        # The internal gate handles disabled config, missing token and policy rights
        # without interrupting already approved collectors.
        try:
            from ingestion.threads_collector import run_collection
            threads = run_collection(root=ROOT, mode='daily')
            threads_status = threads.get('status', 'ERROR')
            threads['ok'] = threads_status == 'COMPLETED'
            if threads_status == 'SKIPPED_CONFIG_DISABLED':
                threads['ok'] = None
            elif threads_status != 'COMPLETED':
                report['warnings'].append(f'Threads: {threads_status}; xem data/reports/threads_daily_latest.json')
            report['stages']['threads'] = threads
            log.write(f'\n[THREADS] status={threads_status} fetched={threads.get("fetched", 0)} new={threads.get("new", 0)} updated={threads.get("updated", 0)}\n')
        except Exception as exc:
            # Do not print potentially credential-bearing network exception strings.
            report['stages']['threads'] = {'ok': False, 'status': 'ERROR', 'error_type': type(exc).__name__}
            report['warnings'].append('Threads: ERROR; các nguồn cũ vẫn tiếp tục')
        if not with_rss:
            report['stages']['rss'] = {'ok': None, 'skipped': 'optional; use --with-rss'}
        elif (ROOT / 'expand_se363.py').exists():
            report['stages']['rss'] = run_command('RSS discovery', ['expand_se363.py', 'rss', '--max-per-feed', str(max_per_feed), '--sleep-seconds', '3'], log)
        else:
            report['stages']['rss'] = {'ok': False, 'error': 'expand_se363.py missing'}
        optional_sources = []
        if read_configured_brands():
            optional_sources.append('brand')
        if read_meta_enabled():
            optional_sources.append('meta')
        if with_partner:
            optional_sources.append('partner')
        if optional_sources and (ROOT / 'collector.py').exists():
            report['stages']['optional_sources'] = run_command(
                'Approved brand / authorized Meta / partner import',
                ['collector.py', '--sources', ','.join(optional_sources)], log)
            report['stages']['optional_sources']['requested_sources'] = optional_sources
        else:
            report['stages']['optional_sources'] = {'ok': True, 'skipped': 'no authorized optional source enabled'}
        if (with_rss or optional_sources) and (ROOT / 'claim_baseline_se363.py').exists() and (RAW / 'posts_auto.jsonl').exists():
            report['stages']['claim_baseline'] = run_command('Claim baseline',
                ['claim_baseline_se363.py', '--out', 'data/auto_baseline', '--reports', 'data/reports'], log)
        if (ROOT / 'claim_baseline_se363.py').exists() and (RAW / 'threads_posts.jsonl').exists():
            report['stages']['threads_claim_baseline'] = run_command('Threads claim candidates',
                ['claim_baseline_se363.py', '--input', 'data/raw/threads_posts.jsonl',
                 '--out', 'data/auto_baseline/threads', '--reports', 'data/reports/threads',
                 '--suppression-db', 'data/state/threads_collector.sqlite'], log)
        if (ROOT / 'expand_se363.py').exists():
            report['stages']['roles_report'] = run_command('Role counts', ['expand_se363.py', 'report'], log)
    report['queued'] = emit_new_events(RAW, STATE, EVENTS)
    scanner_count = report['queued']['events_new']
    threads = report['stages']['threads']
    outbox_count = threads.get('events_emitted', 0)
    report['queued'].update(scanner_events_new=scanner_count,
                            threads_outbox_events_new=outbox_count,
                            events_new=scanner_count + outbox_count)
    if outbox_count:
        roles = report['queued']['by_role']
        roles['threads_post_candidate'] = roles.get('threads_post_candidate', 0) + outbox_count
    report['queued']['spools'] = sorted(set([report['queued']['spool'], *threads.get('event_spools', [])]))
    report['finished_at'] = timestamp()
    report['log_file'] = str(logfile.relative_to(ROOT))
    reports_to_check = ['rss_expansion_report.json'] if with_rss else []
    if 'skipped' not in report['stages']['optional_sources']:
        reports_to_check.append('ingestion_report.json')
    for name in reports_to_check:
        p = REPORTS / name
        if p.exists():
            try:
                obj = json.loads(p.read_text(encoding='utf-8'))
                errs = obj.get('errors', [])
                if errs:
                    report['warnings'].append(f'{name}: có {len(errs)} lỗi từ nguồn/API; xem file report')
            except (OSError, ValueError):
                report['warnings'].append(f'{name}: không đọc được report')
    acceptable_blocks = {'BLOCKED_PERMISSION', 'BLOCKED_POLICY', 'THROTTLED', 'SKIPPED_CONFIG_DISABLED',
                         'PARTIAL', 'QUOTA_EXHAUSTED', 'BUSY'}
    failures = [name for name, status in report['stages'].items() if status.get('ok') is False
                and not (name == 'threads' and status.get('status') in acceptable_blocks)]
    report['status'] = 'FAILED' if failures else ('PARTIAL' if report['warnings'] or report['queued']['warnings'] else 'OK')
    report['failed_stages'] = failures
    report_path = REPORTS / 'daily_latest.json'
    atomic_json(report_path, report)
    history = REPORTS / 'daily_history.jsonl'
    with history.open('a', encoding='utf-8') as h:
        h.write(json.dumps(report, ensure_ascii=False) + '\n')
    print(f'[DAILY] status={report["status"]} events_new={report["queued"]["events_new"]}')
    print(f'[DAILY] log={report["log_file"]}')
    print(f'[DAILY] report={report_path.relative_to(ROOT)}')
    for warn in report['warnings'] + report['queued']['warnings']:
        print(f'[WARN] {warn}')
    return 0 if report['status'] != 'FAILED' else 1


def self_test():
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        raw, state, events = tmp/'raw', tmp/'state.json', tmp/'events'
        raw.mkdir()
        p = raw/'posts_auto.jsonl'
        old = {'_key':'historical', 'source_role':'promotional_content_candidate', 'raw_text':'Old content'}
        p.write_text(json.dumps(old)+'\n', encoding='utf-8')
        initialize_offsets(state, raw)
        assert emit_new_events(raw, state, events)['events_new'] == 0
        with p.open('a',encoding='utf-8') as f:
            f.write(json.dumps({'_key':'new1','source_role':'promotional_content_candidate','raw_text':'Contains vitamin C'})+'\n')
            f.write(json.dumps({'_key':'new2','source_role':'promotional_content_candidate','raw_text':'Supports immunity'})+'\n')
        one = emit_new_events(raw, state, events)
        assert one['events_new'] == 2, one
        two = emit_new_events(raw, state, events)
        assert two['events_new'] == 0, two
        with p.open('a',encoding='utf-8') as f:
            f.write(json.dumps({'_key':'new2','source_role':'promotional_content_candidate','raw_text':'Supports immunity'})+'\n')
        assert emit_new_events(raw, state, events)['events_new'] == 0
        with p.open('a',encoding='utf-8') as f:
            f.write(json.dumps({'_key':'new2','source_role':'promotional_content_candidate','raw_text':'Changed claim'})+'\n')
        assert emit_new_events(raw, state, events)['events_new'] == 1
    print('Self-test PASS: idempotent incremental spool; old data not mislabeled as newly discovered')


def main():
    parser = argparse.ArgumentParser(description='Automated SE363 daily collection; no new dependencies')
    parser.add_argument('--once', action='store_true', help='run one daily collection now')
    parser.add_argument('--self-test', action='store_true')
    parser.add_argument('--status', action='store_true')
    parser.add_argument('--with-partner', action='store_true', help='import updated licensed partner CSV')
    parser.add_argument('--with-rss', action='store_true', help='also collect approved supplementary RSS feeds')
    parser.add_argument('--max-per-feed', type=int, default=50)
    parser.add_argument('--bootstrap-existing', action='store_true', help='replay historical local JSONL records; clearly marked historical')
    a = parser.parse_args()
    if a.self_test:
        return self_test()
    if a.status:
        p = REPORTS/'daily_latest.json'
        print(p.read_text(encoding='utf-8') if p.exists() else 'No daily run recorded yet')
        return
    if a.bootstrap_existing:
        result = emit_new_events(RAW, STATE, EVENTS, historical_replay=True)
        print('[BOOTSTRAP HISTORICAL] queued=', result['events_new'], 'file=', result['spool'])
        for warning in result['warnings']:
            print(f'[WARN] {warning}')
        print('Đây là sự kiện phát lại dữ liệu cũ, KHÔNG phải bản ghi mới được thu hôm nay.')
        return
    if not a.once:
        parser.print_help()
        return
    return daily_once(max_per_feed=a.max_per_feed, with_partner=a.with_partner, with_rss=a.with_rss)


if __name__ == '__main__':
    result = main()
    sys.exit(result if isinstance(result,int) else 0)
